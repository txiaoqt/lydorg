/** Three-column sign-off block with blank signature space for wet signatures. */
export const drawSignatories = (r: OfficialReport) => {
  r.y += 14;
  const center = { halign: "center" as const };
  drawOfficialTable(r, {
    head: OFFICIAL_SIGNATORIES.map(item => ({ content: item.heading, styles: { ...boldStyle(r), ...center, fillColor: OFFICIAL_REPORT_COLORS.lightBlue } })),
    body: [
      OFFICIAL_SIGNATORIES.map(() => ({ content: "", styles: { minCellHeight: 46 } })),
      OFFICIAL_SIGNATORIES.map(item => ({
        content: `${item.position}\nPasig City Youth Development Office`,
        styles: { ...center, cellPadding: { top: 5, bottom: 5, left: 2, right: 2 } },
      })),
    ],
    columnStyles: { 0: { cellWidth: r.width / 3 }, 1: { cellWidth: r.width / 3 }, 2: { cellWidth: r.width / 3 } },
    gapAfter: 32,
  });
};

export const drawNothingFollows = (r: OfficialReport) => {
  // The closing line may sit in the bottom padding above the letterhead footer.
  if (r.y > r.bottom + 10) newPage(r);
  r.doc.setFont("helvetica", "bolditalic");
  r.doc.setFontSize(9);
  r.doc.setTextColor(...OFFICIAL_REPORT_COLORS.text);
  r.doc.text("- - - - -nothing follows- - - - -", (r.left + r.right) / 2, r.y, { align: "center" });
  r.y += 20;
};

/** Centers of Youth Participation in the order the PCYDO reports list them. */
export const CENTERS_OF_YOUTH_PARTICIPATION = [
  "education", "agriculture", "environment", "health", "peace building and security",
  "governance", "active citizenship", "global mobility", "social inclusion and equity", "economic empowerment",
] as const;

const normalizeTheme = (value: string) => value.trim().replace(/\s+/g, " ").replace(/&/g, "and").toLowerCase();

export const formatCenterOfYouthParticipation = (value: string) =>
  normalizeTheme(value).split(" ").map(word => word === "and" ? "&" : word.charAt(0).toUpperCase() + word.slice(1)).join(" ");

export const centerOfYouthParticipationRank = (value: string) => {
  const index = CENTERS_OF_YOUTH_PARTICIPATION.indexOf(normalizeTheme(value) as typeof CENTERS_OF_YOUTH_PARTICIPATION[number]);
  return index === -1 ? CENTERS_OF_YOUTH_PARTICIPATION.length : index;
};

export const percentOf = (count: number, total: number) => total > 0 ? `${((count / total) * 100).toFixed(2)}%` : "0.00%";

const longDate = (isoDate: string) => new Intl.DateTimeFormat("en-US", { timeZone: "UTC", month: "long", day: "numeric", year: "numeric" })
  .format(new Date(`${isoDate}T00:00:00Z`));

/** "The reporting period covers Q4 2026, from October 1, 2026, at 12:00 AM through December 31, 2026, at 11:59:59 PM. …" */
export const describeReportingPeriod = (input: { label: string; startDate?: string | null; endDate?: string | null; referenceDate?: string | null }) => {
  const span = input.startDate && input.endDate
    ? `The reporting period covers ${input.label}, from ${longDate(input.startDate)}, at 12:00 AM through ${longDate(input.endDate)}, at 11:59:59 PM.`
    : `The reporting period covers ${input.label}.`;
  const reference = input.referenceDate
    ? ` Data is counted using the applicable reporting date and the quarter-end reference date of ${longDate(input.referenceDate)}.`
    : " Data is counted using the applicable reporting date.";
  return `${span}${reference} The reporting period follows Philippine Standard Time (UTC+08:00).`;
};

