// Layout and styling follow the PCYDO 2025 letterhead report references (A4 portrait, 1" margins).
type Rgb = [number, number, number];
export const OFFICIAL_REPORT_COLORS = {
  navy: [22, 53, 96] as Rgb,
  lightBlue: [217, 226, 243] as Rgb,
  text: [0, 0, 0] as Rgb,
  muted: [102, 102, 102] as Rgb,
  divider: [136, 136, 136] as Rgb,
  softBorder: [209, 214, 222] as Rgb,
  white: [255, 255, 255] as Rgb,
};

const MARGIN = 72;

export type OfficialReport = {
  doc: jsPDF;
  font: string;
  boldFont: string;
  left: number;
  right: number;
  width: number;
  /** First usable y on continuation pages. */
  top: number;
  /** Last usable y before the letterhead footer. */
  bottom: number;
  y: number;
};

/** Defaults to A4 portrait (the reference layout); honors the paper size/orientation picked in the export dialog. */
export const createOfficialReport = async (pageConfig?: PdfPageConfig): Promise<OfficialReport> => {
  const doc = new jsPDF({
    unit: "pt",
    format: getJsPdfFormat(pageConfig?.paperSize ?? "a4"),
    orientation: pageConfig?.orientation ?? "portrait",
  });
  applyOfficialTemplateBackground(doc);
  await ensurePdfFonts(doc);
  const unicode = Boolean((doc as jsPDF & { __yTraceSegoeFontLoaded?: boolean }).__yTraceSegoeFontLoaded);
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const { headerHeight, footerHeight } = getLetterheadInsets(pageWidth, pageHeight);
  return {
    doc,
    font: unicode ? "SegoeUI" : "helvetica",
    boldFont: unicode ? "SegoeUIBold" : "helvetica",
    left: MARGIN,
    right: pageWidth - MARGIN,
    width: pageWidth - MARGIN * 2,
    top: headerHeight + 8,
    bottom: pageHeight - footerHeight - 16,
    y: headerHeight + 26,
  };
};

const setText = (r: OfficialReport, size: number, bold = false, color: Rgb = OFFICIAL_REPORT_COLORS.text) => {
  r.doc.setFont(bold ? r.boldFont : r.font, bold ? "bold" : "normal");
  r.doc.setFontSize(size);
  r.doc.setTextColor(...color);
};

export const boldStyle = (r: OfficialReport): Partial<Styles> => ({ font: r.boldFont, fontStyle: "bold" });
export const bold = (r: OfficialReport, content: string | number, styles: Partial<Styles> = {}): CellDef =>
  ({ content: String(content), styles: { ...boldStyle(r), ...styles } });

export const ensureSpace = (r: OfficialReport, height: number) => {
  if (r.y + height <= r.bottom) return;
  r.doc.addPage();
  r.y = r.top + 10;
};

export const newPage = (r: OfficialReport) => {
  r.doc.addPage();
  r.y = r.top + 10;
};

export type OfficialHeadingInput = {
  heading: PdfReportHeading;
  /** Big-number row under the heading (label 9pt, value 18pt). */
  metrics?: Array<{ label: string; value: string }>;
  /** Override the generated label; references use both "Generated On" and "Generated". */
  generatedLabel?: string;
};

export const headingDetailLines = (heading: PdfReportHeading) => [
  ...(heading.reportingLines ?? []),
  ...(heading.contextLines ?? []),
  ...(heading.filters?.length ? [`Filters: ${heading.filters.join(" | ")}`] : []),
  ...(heading.sortedBy ? [`Sorted by: ${heading.sortedBy}`] : []),
].filter(line => line.trim());

/** Centered program/title/meta block, optional metrics row, then the grey divider rule. */
export const drawOfficialHeading = (r: OfficialReport, { heading, metrics, generatedLabel = "Generated On" }: OfficialHeadingInput) => {
  const { doc } = r;
  const center = (r.left + r.right) / 2;
  const centered = (text: string, size: number, isBold: boolean, color: Rgb, lineHeight: number) => {
    setText(r, size, isBold, color);
    const lines = doc.splitTextToSize(text, r.width) as string[];
    lines.forEach((line, index) => doc.text(line, center, r.y + index * lineHeight, { align: "center" }));
    r.y += (lines.length - 1) * lineHeight;
  };

  centered(heading.programTitle, 14, true, OFFICIAL_REPORT_COLORS.text, 17);
  r.y += 24;
  centered(heading.title, 18, true, OFFICIAL_REPORT_COLORS.text, 21);
  r.y += 16;
  const generated = `${generatedLabel}: ${formatReportGeneratedAt(heading.generatedAt)}${heading.generatedBy ? ` | Generated by: ${heading.generatedBy}` : ""}`;
  centered(generated, 9, false, OFFICIAL_REPORT_COLORS.text, 12);
  for (const line of headingDetailLines(heading)) {
    r.y += 12.5;
    centered(line, 9, false, OFFICIAL_REPORT_COLORS.muted, 12);
  }

  if (metrics?.length) {
    r.y += 30;
    const columnWidth = r.width / metrics.length;
    let valueLines = 1;
    metrics.forEach((metric, index) => {
      const x = r.left + 5 + index * columnWidth;
      let labelSize = 9;
      setText(r, labelSize);
      while (labelSize > 7.5 && doc.getTextWidth(metric.label) > columnWidth - 10) setText(r, (labelSize -= 0.5));
      doc.text(doc.splitTextToSize(metric.label, columnWidth - 10)[0] ?? "", x, r.y);
      // Shrink long values (e.g. organization names, peso amounts) to fit one line before wrapping.
      let size = 18;
      setText(r, size, true);
      while (size > 13 && doc.getTextWidth(metric.value) > columnWidth - 16) setText(r, --size, true);
      const lines = doc.splitTextToSize(metric.value, columnWidth - 10) as string[];
      lines.forEach((line, lineIndex) => doc.text(line, x, r.y + 20 + lineIndex * 21));
      valueLines = Math.max(valueLines, lines.length);
    });
    r.y += 40 + (valueLines - 1) * 21;
  } else {
    r.y += 25;
  }

  doc.setDrawColor(...OFFICIAL_REPORT_COLORS.divider);
  doc.setLineWidth(0.75);
  doc.line(r.left + 4, r.y, r.right - 4, r.y);
  r.y += 25;
};

/** "A.  Organization Profile" (12pt) or "I. Reporting Scope and Period" (11pt). */
export const drawSectionTitle = (r: OfficialReport, text: string, size: 11 | 12 = 12) => {
  ensureSpace(r, 70);
  setText(r, size, true);
  r.doc.text(text, r.left, r.y);
  r.y += size === 12 ? 18 : 14;
};

export type OfficialTableInput = {
  /** Navy title bar spanning every column. */
  title?: string;
  /** Column header row. "plain" = bold black on white (default); "navy" = white on navy, used when there is no title bar. */
  head?: Array<string | CellDef>;
  headStyle?: "plain" | "navy";
  body: RowInput[];
  columnStyles?: Record<number, Partial<Styles>>;
  fontSize?: 8 | 9 | 10;
  border?: "soft" | "black";
  columnCount?: number;
  gapAfter?: number;
  valign?: "middle" | "top";
};

export const drawOfficialTable = (r: OfficialReport, input: OfficialTableInput) => {
  const spanOf = (cell: unknown) => typeof cell === "object" && cell !== null && "colSpan" in cell ? Number((cell as CellDef).colSpan ?? 1) : 1;
  const columnCount = input.columnCount ?? input.head?.length
    ?? Math.max(1, ...input.body.map(row => Array.isArray(row) ? (row as unknown[]).reduce<number>((sum, cell) => sum + spanOf(cell), 0) : 1));
  const fontSize = input.fontSize ?? 9;
  const navyHead: Partial<Styles> = { fillColor: OFFICIAL_REPORT_COLORS.navy, textColor: OFFICIAL_REPORT_COLORS.white, ...boldStyle(r) };
  const head: RowInput[] = [];
  if (input.title) head.push([{ content: input.title, colSpan: columnCount, styles: navyHead }]);
  if (input.head) head.push(input.head.map(cell => typeof cell === "string"
    ? { content: cell, styles: input.headStyle === "navy" ? navyHead : { ...boldStyle(r), fillColor: false as const, textColor: OFFICIAL_REPORT_COLORS.text } }
    : cell));

  ensureSpace(r, 70);
  const pageHeight = r.doc.internal.pageSize.getHeight();
  autoTable(r.doc, {
    startY: r.y,
    margin: { left: r.left, right: r.doc.internal.pageSize.getWidth() - r.right, top: r.top, bottom: pageHeight - r.bottom },
    head,
    body: input.body,
    theme: "grid",
    showHead: "firstPage",
    rowPageBreak: "avoid",
    tableWidth: r.width,
    styles: {
      font: r.font,
      fontStyle: "normal",
      fontSize,
      cellPadding: fontSize === 8 ? { top: 4.5, bottom: 4.5, left: 3, right: 3 } : { top: fontSize === 10 ? 6.5 : 6, bottom: fontSize === 10 ? 6.5 : 6, left: 5, right: 5 },
      lineColor: input.border === "soft" ? OFFICIAL_REPORT_COLORS.softBorder : OFFICIAL_REPORT_COLORS.text,
      lineWidth: 0.75,
      textColor: OFFICIAL_REPORT_COLORS.text,
      fillColor: false,
      valign: input.valign ?? "middle",
      overflow: "linebreak",
    },
    headStyles: { fillColor: false, textColor: OFFICIAL_REPORT_COLORS.text },
    bodyStyles: { fillColor: false },
    columnStyles: input.columnStyles ?? {},
  });
  r.y = (r.doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + (input.gapAfter ?? 18);
};

/** Light-blue full-width row used for district groupings inside a table. */
export const groupRow = (r: OfficialReport, label: string, columnCount: number): RowInput =>
  [{ content: label, colSpan: columnCount, styles: { ...boldStyle(r), halign: "left", fillColor: OFFICIAL_REPORT_COLORS.lightBlue } }];

/** Muted, justified explanatory paragraph (e.g. non-additive advocacy note). */
export const drawNote = (r: OfficialReport, text: string) => {
  setText(r, 9, false, OFFICIAL_REPORT_COLORS.muted);
  const lines = r.doc.splitTextToSize(text, r.width - 10) as string[];
  ensureSpace(r, lines.length * 12 + 8);
  r.y -= 6;
  lines.forEach((line, index) => {
    const y = r.y + index * 11.7;
    if (index === lines.length - 1) r.doc.text(line, r.left + 5, y);
    else drawJustifiedLine(r.doc, line, r.left + 5, y, r.width - 10);
  });
  r.y += lines.length * 11.7 + 16;
};

/** Draws one line stretched to `width` by widening the gaps between words. */
const drawJustifiedLine = (doc: jsPDF, line: string, x: number, y: number, width: number) => {
  const words = line.split(" ").filter(Boolean);
  if (words.length < 2) {
    doc.text(line, x, y);
    return;
  }
  const wordsWidth = words.reduce((sum, word) => sum + doc.getTextWidth(word), 0);
  const gap = (width - wordsWidth) / (words.length - 1);
  let cursor = x;
  for (const word of words) {
    doc.text(word, cursor, y);
    cursor += doc.getTextWidth(word) + gap;
  }
};

/** "● Lead. Body" bullets with a bold lead-in, justified like the reference. */
export const drawBullets = (r: OfficialReport, items: Array<{ lead: string; text: string }>) => {
  const { doc } = r;
  const indent = 9;
  const textWidth = r.width - indent;
  const lineHeight = 14;
  for (const item of items) {
    setText(r, 10, true);
    const leadWidth = doc.getTextWidth(`${item.lead} `);
    setText(r, 10);
    // Lay out the body around the bold lead on the first line.
    const words = item.text.split(/\s+/);
    const lines: string[] = [];
    let current = "";
    let available = textWidth - leadWidth;
    for (const word of words) {
      const candidate = current ? `${current} ${word}` : word;
      if (doc.getTextWidth(candidate) > available && current) {
        lines.push(current);
        current = word;
        available = textWidth;
      } else current = candidate;
    }
    if (current) lines.push(current);
    ensureSpace(r, lines.length * lineHeight + 4);
    setText(r, 10);
    doc.text("\u25CF", r.left, r.y);
    setText(r, 10, true);
    doc.text(item.lead, r.left + indent, r.y);
    setText(r, 10);
    lines.forEach((line, index) => {
      const x = index === 0 ? r.left + indent + leadWidth : r.left + indent;
      const width = index === 0 ? textWidth - leadWidth : textWidth;
      if (index === lines.length - 1) doc.text(line, x, r.y + index * lineHeight);
      else drawJustifiedLine(doc, line, x, r.y + index * lineHeight, width);
    });
    r.y += lines.length * lineHeight;
  }
  r.y += 12;
};

