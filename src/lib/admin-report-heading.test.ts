import { jsPDF } from "jspdf";
import { describe, expect, it, vi } from "vitest";
import { buildAdminReportHeading, describeAllocationReportOrder, describeReportOrder, reportFilterValue } from "./admin-report-heading";
import { buildPdfHeaderLayout, buildCsvContent, generateReportPdfDocument, renderPdfPageDecoration } from "./report-export";
import type { AdminReportPeriod } from "./admin-report-period";

const generatedAt = new Date("2026-10-18T09:16:00Z");
const quarter = { mode: "quarter", year: 2026, quarter: 4 } as const;
const config = {
  title: "Existing table title", filenamePrefix: "existing-file", columns: [
    { label: "Organization", value: (row: { organization: string; amount: number }) => row.organization, pdfWidth: 120 },
    { label: "Amount", value: (row: { organization: string; amount: number }) => row.amount, pdfWidth: 80 },
  ],
};

describe("dynamic Admin report headings", () => {
  it.each([
    ["system", "Activity Logs Report", "Y-TRACE"], ["system", "Administrators Report", "Y-TRACE"],
    ["yorp", "Registry Report", "Youth Organization Registration Program"],
    ["yorp", "Organization Report", "Youth Organization Registration Program"],
    ["ypop", "1st Semester Budget Requests Report", "Youth Participation Organization Passport"],
    ["ypop", "Liquidation Reports", "Youth Participation Organization Passport"],
    ["office", "Budget Monitoring Report", "Pasig City Youth Development Office"],
    ["office", "Budget Allocation by Barangay Report", "Pasig City Youth Development Office"],
    ["yorp", "Quarterly Summary Report", "Youth Organization Registration Program"],
    ["yorp", "Disaggregated Report", "Youth Organization Registration Program"],
  ] as const)("uses the report-specific %s program for %s", (program, title, programTitle) => {
    const heading = buildAdminReportHeading({ program, title, period: quarter, generatedBy: "Example Administrator", generatedAt });
    expect(heading.programTitle).toBe(programTitle);
    expect(heading.title).toBe(`${title} — Q4 2026`);
    expect(heading.reportingLines).toEqual(["Reporting Period: Q4 2026 | Date Range: 2026-10-01 – 2026-12-31 (Asia/Manila)"]);
  });

  it.each<AdminReportPeriod>([
    { mode: "all" }, { mode: "year", year: 2025 }, { mode: "quarter_all_years", quarter: 2 },
    { mode: "custom", startDate: "2026-02-03", endDate: "2026-02-18" },
  ])("uses the chosen period without a hardcoded quarter (%j)", period => {
    const heading = buildAdminReportHeading({ program: "yorp", title: "Registry Report", period });
    expect(heading.title).not.toContain("Q4 2026");
    if (period.mode === "all") expect(heading.title).toBe("Registry Report");
    if (period.mode === "custom") expect(heading.reportingLines![0]).toContain("2026-02-03 – 2026-02-18");
  });

  it("preserves filtered context, names and one Asia/Manila generation timestamp", async () => {
    const heading = buildAdminReportHeading({ program: "system", title: "Activity Logs Report", generatedAt,
      generatedBy: "Example Dela Peña", reportingLines: ["Reporting Period: Last 7 days"],
      filters: ["Category: Budget", "Search: Reviewed"], sortedBy: "Date and Time (Newest first)" });
    const layout = await buildPdfHeaderLayout(new jsPDF({ unit: "pt" }), { config, rows: [], pdfHeading: heading }, 30, 30);
    expect(layout.detailLines[0]).toMatch(/^Generated On: October 18, 2026 at 5:16 PM \| Generated by: Example Dela Peña$/);
    expect(layout.detailLines).toContain("Reporting Period: Last 7 days");
    expect(layout.detailLines).toContain("Filters: Category: Budget | Search: Reviewed");
    expect(layout.detailLines).toContain("Sorted by: Date and Time (Newest first)");
    expect(layout.detailLines.join(" ")).not.toContain("All Periods");
    expect(layout.detailLines.join(" ")).not.toContain("October 16");
  });

  it("does not retain private session context or invent unsupported filters", () => {
    const heading = buildAdminReportHeading({ program: "yorp", title: "Organization Report", generatedBy: "Example Admin",
      ...{ sessionToken: "PRIVATE_SYNTHETIC_CANARY" } });
    expect(JSON.stringify(heading)).not.toContain("PRIVATE_SYNTHETIC_CANARY");
    expect(heading.filters).toBeUndefined();
    expect(heading.sortedBy).toBeUndefined();
  });

  it("describes real supplied row order without sorting or mutating the export", () => {
    const rule = { label: "Name (A-Z)", compare: (a: string, b: string) => a.localeCompare(b) };
    const rows = ["Zulu", "Alpha"];
    expect(describeReportOrder(rows, [rule], "Current order")).toBe("Current order");
    expect(rows).toEqual(["Zulu", "Alpha"]);
    expect(describeReportOrder(["Alpha", "Zulu"], [rule], "Current order")).toBe("Name (A-Z)");
    expect(reportFilterValue("all")).toBe("All");
    expect(reportFilterValue("needs_revision")).toBe("Needs Revision");
  });

  it.each([
    ["org_asc", "District, then Barangay Name (A-Z)"],
    ["category_desc", "District, then Barangay Name (Z-A)"],
    ["approved_desc", "District, then Approved Amount (Highest first), then Barangay Name (A-Z)"],
    ["released_asc", "District, then Released Amount (Lowest first), then Barangay Name (A-Z)"],
  ])("describes the actual allocation comparator for %s", (sort, expected) => {
    expect(describeAllocationReportOrder(sort)).toBe(expected);
  });
});

describe("actual centered PDF layout and preserved tables", () => {
  it.each(["portrait", "landscape"] as const)("wraps long headings and places summary totals above the table (%s)", async orientation => {
    const doc = new jsPDF({ unit: "pt", format: "a4", orientation });
    const heading = buildAdminReportHeading({ program: "office", title: "Budget Monitoring Report", period: quarter, generatedAt,
      generatedBy: "Example Administrator With A Long Display Name",
      filters: ["District: District II", "Barangay: Pinagbuhatan", "Classification: Youth-Serving Organization", `Search: ${"Community Leadership ".repeat(8)}`],
      sortedBy: "Risk level, then Approved Amount (Highest first)", summaryMetrics: [
        { label: "Total Monitored Records", value: "25" }, { label: "Total Approved Amount", value: "PHP 1,234,567.89" },
        { label: "Total Released Amount", value: "PHP 987,654.32" }, { label: "Total Remaining Amount", value: "PHP 246,913.57" },
      ] });
    const layout = await buildPdfHeaderLayout(doc, { config, rows: [], pdfHeading: heading }, 30, 30);
    expect(layout.headingLines!.some(line => line.text.length > 1)).toBe(true);
    expect(layout.summaryMetrics).toHaveLength(4);
    expect(layout.summaryMetrics!.every(metric => metric.x >= 30 && metric.x < layout.pageWidth - 30)).toBe(true);
    expect(layout.startY).toBeGreaterThan(Math.max(...layout.summaryMetrics!.map(metric => metric.valueY + metric.value.length * 19.5)));
    const text = vi.spyOn(doc, "text");
    renderPdfPageDecoration(doc, layout, 1, 2);
    for (const line of layout.headingLines!) {
      expect(text).toHaveBeenCalledWith(line.text, layout.pageWidth / 2, line.y, expect.objectContaining({ align: "center" }));
    }
    text.mockClear();
    renderPdfPageDecoration(doc, layout, 2, 2);
    expect(text.mock.calls.some(([value]) => Array.isArray(value) && value.includes(heading.title))).toBe(false);
  });

  it("retains the original table columns, rows, totals and CSV bytes", async () => {
    const rows = [{ organization: "Sample Youth Organization", amount: 12500 }];
    const base = { config, rows, totalsRow: ["TOTAL", 12500] };
    const csv = buildCsvContent(base);
    const pdfHeading = buildAdminReportHeading({ program: "office", title: "Budget Monitoring Report", generatedAt,
      filters: ["District: All"], summaryMetrics: [{ label: "Total Records", value: "1" }] });
    const pdf = await generateReportPdfDocument({ ...base, pdfHeading });
    const table = (pdf as unknown as { lastAutoTable: {
      head: Array<{ cells: Record<number, { text: string[] }> }>;
      body: Array<{ cells: Record<number, { text: string[] }> }>;
      foot: Array<{ cells: Record<number, { text: string[] }> }>;
      columns: Array<{ width: number }>;
    } }).lastAutoTable;
    expect(table.head[0].cells[0].text).toEqual(["Organization"]);
    expect(table.head[0].cells[1].text).toEqual(["Amount"]);
    expect(table.body[0].cells[0].text.join(" ")).toBe("Sample Youth Organization");
    expect(table.body[0].cells[1].text).toEqual(["12500"]);
    expect(table.foot[0].cells[0].text).toEqual(["TOTAL"]);
    expect(table.columns.reduce((sum, column) => sum + column.width, 0)).toBeCloseTo(pdf.internal.pageSize.getWidth() - 60, 1);
    expect(buildCsvContent({ ...base, pdfHeading })).toBe(csv);
  });

  it("rejects a heading that would push the table off the page", async () => {
    const doc = new jsPDF({ unit: "pt" });
    const pdfHeading = buildAdminReportHeading({ program: "office", title: "Report", filters: ["Long search ".repeat(2000)] });
    await expect(buildPdfHeaderLayout(doc, { config, rows: [], pdfHeading }, 30, 30)).rejects.toThrow("heading is too long");
  });
});
