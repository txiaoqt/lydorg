function resolveSampleBudgetPurpose(activityTitle: string, advocacies: string[]): string {
  const title = activityTitle.trim().toLowerCase();
  const preferred = title.includes("disaster") || title.includes("security") || title.includes("first aid")
    ? "peace building and security"
    : title.includes("leadership") || title.includes("governance") || title.includes("planning")
      ? "governance"
      : title.includes("education") || title.includes("academic") || title.includes("technology")
        ? "education"
        : title.includes("sport") || title.includes("fitness") || title.includes("wellness")
          ? "health"
          : title.includes("environment") || title.includes("tree-planting") || title.includes("greening")
            ? "environment"
            : title.includes("community") || title.includes("civic") || title.includes("outreach") || title.includes("clean-up")
              ? "social inclusion and equity"
              : title.includes("arts") || title.includes("culture")
                ? "education"
                : null;

  return advocacies.find((advocacy) => advocacy.trim().toLowerCase() === preferred)
    ?? advocacies.find((advocacy) => advocacy.trim().length > 0)
    ?? "";
}
