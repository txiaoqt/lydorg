-- Run this in the Supabase SQL editor.
-- Sets up the backend for the new Administrators (Accounts) page:
-- a units table, admin_accounts.role_id/unit_id linkage, and the RPCs the
-- admin portal needs to list/create/edit/suspend/delete administrators.
--
-- CONFIRMED: the `roles.code` column is typed `app_role_code`, a Postgres
-- enum shared with the rest of the app (it also holds 'organization_user'
-- and 'youth'). It only had 'admin' — no 'super_admin' — so STEP 1 below
-- adds that value to the enum.
--
-- >>> RUN STEP 1 BY ITSELF FIRST, THEN RUN STEP 2 (everything else) <<<
-- Postgres will not let a newly added enum value be used in the same
-- transaction/script that added it, so these must be two separate
-- SQL editor runs or you'll get an "unsafe use of new value" error.
--
-- ASSUMPTION: password_hash is verified with pgcrypto bcrypt
-- (crypt(password, password_hash) = password_hash). If your login RPC uses
-- something else, create_admin_account below will produce accounts that
-- can't log in — let me know and I'll adjust.
--
-- SECURITY: every mutating RPC below (create/update/suspend/delete) requires
-- the caller to hold the 'super_admin' role, not just any authenticated
-- admin session — otherwise a freshly created low-privilege Admin account
-- could create other accounts, delete admins, or escalate its own role.
-- update_admin_account additionally blocks a caller from changing their own
-- role_id, so a super admin can't accidentally (or a compromised session
-- can't deliberately) demote themselves out of the only account that can
-- still manage roles.

-- ============================================================
-- STEP 1 — run this statement alone, then come back for STEP 2.
-- ============================================================
alter type public.app_role_code add value if not exists 'super_admin';

-- ============================================================
-- STEP 2 — run everything below this line after STEP 1 has
-- completed (in a separate query execution).
-- ============================================================

create extension if not exists pgcrypto;

create table if not exists public.units (
  id smallint generated by default as identity not null,
  code text not null,
  label text not null,
  description text null,
  created_at timestamp with time zone not null default now(),
  constraint units_pkey primary key (id),
  constraint units_code_key unique (code)
);

insert into public.units (code, label)
values
  ('administration_finance', 'Administration & Finance'),
  ('programs_operations', 'Programs & Operations'),
  ('policy_planning_monitoring', 'Policy, Planning, & Monitoring')
on conflict (code) do nothing;

insert into public.roles (code, label)
values
  ('super_admin', 'Super Admin'),
  ('admin', 'Admin')
on conflict (code) do nothing;

alter table public.admin_accounts
  add column if not exists role_id smallint references public.roles(id),
  add column if not exists unit_id smallint references public.units(id);

create or replace function public.list_roles_for_admin_portal(_session_token text)
returns table (id smallint, code text, label text)
language plpgsql
security definer
set search_path = public
as $$
declare
  _admin_id uuid;
begin
  select vat.admin_id into _admin_id
  from public.validate_admin_session_token(_session_token) vat
  limit 1;

  if _admin_id is null then
    raise exception 'Admin account is not authorized.';
  end if;

  return query
  select r.id, r.code::text, r.label from public.roles r order by r.id asc;
end;
$$;

