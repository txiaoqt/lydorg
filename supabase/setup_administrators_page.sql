create or replace function public.list_administrators_for_admin_portal(_session_token text)
returns table (
  id uuid,
  display_name text,
  email text,
  username text,
  role_code text,
  role_label text,
  unit_code text,
  unit_label text,
  is_active boolean,
  last_active_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  _admin_id uuid;
begin
  select vat.admin_id into _admin_id
  from public.validate_admin_session_token(_session_token) vat
  limit 1;

  if _admin_id is null then
    raise exception 'Admin account is not authorized.';
  end if;

  return query
  select
    aa.id,
    aa.display_name,
    aa.email::text,
    aa.username::text,
    r.code::text,
    r.label,
    u.code,
    u.label,
    aa.is_active,
    (select max(s.last_used_at) from public.admin_sessions s where s.admin_id = aa.id)
  from public.admin_accounts aa
  left join public.roles r on r.id = aa.role_id
  left join public.units u on u.id = aa.unit_id
  order by aa.display_name asc;
end;
$$;

create or replace function public.create_admin_account(
  _session_token text,
  _display_name text,
  _email text,
  _username text,
  _password text,
  _role_id smallint,
  _unit_id smallint
)
returns table (id uuid, display_name text, email text, username text, role_id smallint, unit_id smallint, is_active boolean)
language plpgsql
security definer
set search_path = public
as $$
declare
  _admin_id uuid;
begin
  select vat.admin_id into _admin_id
  from public.validate_admin_session_token(_session_token) vat
  limit 1;

  if _admin_id is null then
    raise exception 'Admin account is not authorized.';
  end if;

  if not exists (
    select 1 from public.admin_accounts a
    join public.roles r on r.id = a.role_id
    where a.id = _admin_id and r.code = 'super_admin'
  ) then
    raise exception 'Only super administrators may manage admin accounts.';
  end if;

  return query
  insert into public.admin_accounts (display_name, email, username, password_hash, role_id, unit_id)
  values (
    trim(_display_name),
    trim(_email),
    trim(_username),
    crypt(_password, gen_salt('bf')),
    _role_id,
    _unit_id
  )
  returning admin_accounts.id, admin_accounts.display_name, admin_accounts.email::text, admin_accounts.username::text, admin_accounts.role_id, admin_accounts.unit_id, admin_accounts.is_active;
end;
$$;

create or replace function public.update_admin_account(
  _session_token text,
  _admin_id_to_update uuid,
  _display_name text,
  _email text,
  _username text,
  _role_id smallint,
  _unit_id smallint
)
returns table (id uuid, display_name text, email text, username text, role_id smallint, unit_id smallint, is_active boolean)
language plpgsql
security definer
set search_path = public
as $$
declare
  _admin_id uuid;
begin
  select vat.admin_id into _admin_id
  from public.validate_admin_session_token(_session_token) vat
  limit 1;

  if _admin_id is null then
    raise exception 'Admin account is not authorized.';
  end if;

  if not exists (
    select 1 from public.admin_accounts a
    join public.roles r on r.id = a.role_id
    where a.id = _admin_id and r.code = 'super_admin'
  ) then
    raise exception 'Only super administrators may manage admin accounts.';
  end if;

  if _admin_id = _admin_id_to_update and _role_id is distinct from (select role_id from public.admin_accounts where id = _admin_id) then
    raise exception 'You cannot change your own role.';
  end if;

  return query
  update public.admin_accounts
  set
    display_name = trim(_display_name),
    email = trim(_email),
    username = trim(_username),
    role_id = _role_id,
    unit_id = _unit_id,
    updated_at = now()
  where admin_accounts.id = _admin_id_to_update
  returning admin_accounts.id, admin_accounts.display_name, admin_accounts.email::text, admin_accounts.username::text, admin_accounts.role_id, admin_accounts.unit_id, admin_accounts.is_active;
end;
$$;

